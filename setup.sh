#!/usr/bin/env bash
#
# setup.sh — One-time local development setup for mycadet.
#
# Installs workspace dependencies, registers local packages as linkable,
# links them into the meta package, and then links the global `cadet`
# command to the local meta entry point.
#
# Usage:
#   ./setup.sh

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "$0")" && pwd)"

info()  { echo "==> $*"; }
error() { echo "error: $*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# Pre-flight: ensure bun is available (install automatically if missing)
# ---------------------------------------------------------------------------
# Keep this version in sync with .tool-versions (bun).
EXPECTED_BUN_VERSION="1.3.11"

if ! command -v bun &>/dev/null; then
  info "Bun not found — installing bun-v${EXPECTED_BUN_VERSION} from https://bun.sh"
  curl -fsSL https://bun.sh/install | bash -s "bun-v${EXPECTED_BUN_VERSION}"
  # Add bun to PATH for the rest of this script
  export BUN_INSTALL="${HOME}/.bun"
  export PATH="${BUN_INSTALL}/bin:${PATH}"
  if ! command -v bun &>/dev/null; then
    error "Bun installation failed. Install it manually from https://bun.sh and try again."
  fi
  installed_bun_version="$(bun --version)"
  info "Bun ${installed_bun_version} installed successfully"
  if [ "${installed_bun_version}" != "${EXPECTED_BUN_VERSION}" ]; then
    echo "warning: installed bun ${installed_bun_version} does not match expected ${EXPECTED_BUN_VERSION} (keep setup.sh and .tool-versions in sync when upgrading)" >&2
  fi
fi

# ---------------------------------------------------------------------------
# Configure git to use .githooks/ for pre-commit hooks (works in worktrees)
# ---------------------------------------------------------------------------
info "Configuring git hooks"
git config core.hooksPath .githooks

# ---------------------------------------------------------------------------
# Install workspace dependencies (one install covers every member)
# ---------------------------------------------------------------------------
info "Installing workspace dependencies"
(cd "${REPO_ROOT}" && bun install)

# ---------------------------------------------------------------------------
# Register local packages as linkable
# ---------------------------------------------------------------------------
for dir in cli gateway assistant credential-executor; do
  info "Registering ${dir}/ as a linkable package"
  (cd "${REPO_ROOT}/${dir}" && bun link)
done

# ---------------------------------------------------------------------------
# Install dependencies for scripts/
# ---------------------------------------------------------------------------
info "Installing dependencies in scripts/"
(cd "${REPO_ROOT}/scripts" && bun install)

# ---------------------------------------------------------------------------
# Link local packages into meta so it resolves to local source
# ---------------------------------------------------------------------------
info "Linking local packages into meta/"
(cd "${REPO_ROOT}/meta" && bun link @mycadet/cli @mycadet/assistant @mycadet/gateway @mycadet/credential-executor)

# ---------------------------------------------------------------------------
# Link the global `cadet` command to this repo's meta package
# ---------------------------------------------------------------------------
info "Linking global 'cadet' command to meta/"
(cd "${REPO_ROOT}/meta" && bun link)

# ---------------------------------------------------------------------------
# Link the global `cadet-local` command to this checkout's source, pinned to
# the local environment
# ---------------------------------------------------------------------------
# `cadet` resolves its environment from its own version (a source checkout
# resolves to production), and non-production environments install as
# `cadet-<env>` — the CLI's own next-steps printout advertises `cadet-local`
# for the local seed (localhost cloud/web URLs + its own state dirs). This
# shim IS that command: it runs THIS checkout's CLI source directly with the
# local environment pinned — no install or build step.
info "Linking global 'cadet-local' command to local source (CADET_ENVIRONMENT=local)"
mkdir -p "${HOME}/.bun/bin"
cat > "${HOME}/.bun/bin/cadet-local" << CADET_LOCAL_SHIM
#!/usr/bin/env bash
# Generated by setup.sh against the checkout at ${REPO_ROOT}.
# Re-run setup.sh after moving that checkout.
export CADET_ENVIRONMENT=local
exec bun "${REPO_ROOT}/cli/src/index.ts" "\$@"
CADET_LOCAL_SHIM
chmod +x "${HOME}/.bun/bin/cadet-local"

# ---------------------------------------------------------------------------
# Install shell completions for the `cadet` command
# ---------------------------------------------------------------------------
info "Installing shell completions for cadet"

CADET_COMP_DIR="${HOME}/.config/cadet/completions"
mkdir -p "${CADET_COMP_DIR}"

LOCKFILE_PATH="${HOME}/.cadet.lock.json"
LOCKFILE_GREP="grep -o '\"assistantId\"[[:space:]]*:[[:space:]]*\"[^\"]*\"' ${LOCKFILE_PATH} 2>/dev/null | awk -F'\"' '{print \$(NF-1)}'"

# — Bash completions —
cat > "${CADET_COMP_DIR}/completions.bash" << 'BASH_COMP'
_cadet_completions() {
  local cur prev commands
  COMPREPLY=()
  cur="${COMP_WORDS[COMP_CWORD]}"
  prev="${COMP_WORDS[COMP_CWORD-1]}"
  commands="client hatch ps retire sleep wake"

  if [[ ${COMP_CWORD} -eq 1 ]]; then
    COMPREPLY=( $(compgen -W "${commands}" -- "${cur}") )
    return 0
  fi

  case "${COMP_WORDS[1]}" in
    hatch)
      COMPREPLY=( $(compgen -W "openclaw cadet -d --name --remote" -- "${cur}") )
      ;;
    client|retire)
      local instances
BASH_COMP

# Append the dynamic lockfile lookup (needs variable expansion)
cat >> "${CADET_COMP_DIR}/completions.bash" << BASH_COMP_DYN
      instances="\$(${LOCKFILE_GREP} | tr '\n' ' ')"
BASH_COMP_DYN

cat >> "${CADET_COMP_DIR}/completions.bash" << 'BASH_COMP_END'
      COMPREPLY=( $(compgen -W "${instances}" -- "${cur}") )
      ;;
  esac

  return 0
}

complete -F _cadet_completions cadet
complete -F _cadet_completions cadet-local
BASH_COMP_END

# — Zsh completions —
cat > "${CADET_COMP_DIR}/completions.zsh" << 'ZSH_COMP'
_cadet() {
  local -a commands
  commands=(
    'client'
    'hatch'
    'ps'
    'retire'
    'sleep'
    'wake'
  )

  _arguments -C \
    '1:command:->command' \
    '*::arg:->args'

  case $state in
    command)
      _describe 'command' commands
      ;;
    args)
      case $words[1] in
        hatch)
          _arguments '*:species:(openclaw cadet -d --name --remote)'
          ;;
        client|retire)
          local -a instances
ZSH_COMP

# Append the dynamic lockfile lookup (needs variable expansion)
cat >> "${CADET_COMP_DIR}/completions.zsh" << ZSH_COMP_DYN
          instances=(\${(f)"\$(${LOCKFILE_GREP})"})
ZSH_COMP_DYN

cat >> "${CADET_COMP_DIR}/completions.zsh" << 'ZSH_COMP_END'
          _describe 'instance' instances
          ;;
      esac
      ;;
  esac
}

compdef _cadet cadet
compdef _cadet cadet-local
ZSH_COMP_END

# ---------------------------------------------------------------------------
# Wire up PATH + completions in shell rc files.
#
# nix / home-manager manage ~/.zshrc (and friends) as read-only symlinks into
# the nix store. When the canonical rc isn't writable, fall back to a writable
# "*.local" escape hatch it already sources (e.g. ~/.zshrc sources
# ~/.zshenv.local) so our additions still load. If no hatch is found we use a
# "<rc>.local" sidecar and tell the user to source it from their config.
# ---------------------------------------------------------------------------
BUN_BIN="${HOME}/.bun/bin"

# Echo the writable file to append to for a given canonical rc.
rc_target() {
  local rc="$1"
  if [ -w "$rc" ]; then
    printf '%s' "$rc"
    return
  fi
  # Read-only rc (nix symlink): reuse a "source ~/...local" hatch it already
  # sources; otherwise fall back to a "<rc>.local" sidecar.
  local hatch
  hatch="$(sed -n 's/.*source[[:space:]]*\(~[^ ;&]*\.local\).*/\1/p' "$rc" 2>/dev/null | head -1)"
  if [ -n "$hatch" ]; then
    printf '%s' "${hatch/#\~/$HOME}"
  else
    printf '%s' "${rc}.local"
  fi
}

# Warn if our chosen target isn't actually sourced by the canonical rc.
warn_unsourced() {
  local rc="$1" target="$2"
  [ "$rc" = "$target" ] && return
  if ! grep -qF "$(basename "$target")" "$rc" 2>/dev/null; then
    echo "warning: ${rc} is read-only and does not source ${target}." >&2
    echo "         Add this to your shell config so completions load:" >&2
    echo "         [[ -f ${target} ]] && source ${target}" >&2
  fi
}

# — Ensure ~/.bun/bin is on PATH in shell rc files —
for rc in "${HOME}/.bashrc" "${HOME}/.zshrc"; do
  [ -e "$rc" ] || continue
  target="$(rc_target "$rc")"
  warn_unsourced "$rc" "$target"
  [ -e "$target" ] || touch "$target"
  if ! grep -qF "${BUN_BIN}" "$target"; then
    printf '\nexport PATH="%s:$PATH"\n' "${BUN_BIN}" >> "$target"
  fi
done

# — Source completions from shell rc files —
if [ -e "${HOME}/.bashrc" ]; then
  target="$(rc_target "${HOME}/.bashrc")"
  [ -e "$target" ] || touch "$target"
  if ! grep -qF '.config/cadet/completions/completions.bash' "$target"; then
    printf '\n# cadet completions\nsource ~/.config/cadet/completions/completions.bash\n' >> "$target"
  fi
fi

if [ -e "${HOME}/.zshrc" ]; then
  target="$(rc_target "${HOME}/.zshrc")"
  [ -e "$target" ] || touch "$target"
  if ! grep -qF '.config/cadet/completions/completions.zsh' "$target"; then
    # The escape hatch may be sourced before compinit defines `compdef`, so
    # ensure the completion system is initialized before sourcing.
    {
      printf '\n# cadet completions\n'
      printf 'if ! whence compdef >/dev/null 2>&1; then autoload -Uz compinit && compinit; fi\n'
      printf 'source ~/.config/cadet/completions/completions.zsh\n'
    } >> "$target"
  fi
fi

info "Setup complete! Run 'cadet --version' to verify."
