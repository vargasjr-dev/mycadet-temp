/**
 * The local exec's service semantics — which directory a command runs in.
 * The one local instance dir carries all three services' roots (the docker
 * statefulset's per-service mounts, flattened onto one directory): the
 * assistant works in the workspace, the gateway's files live in its
 * security dir, and the credential-executor writes its data root. The CLI's
 * exec command asks this instead of inlining the mapping, so the baseten
 * wrap (whose `cadet exec` resolves the same service to the same directory
 * inside the sandbox) and the local spawn cannot drift.
 */

import { chmodSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import type { ServiceName } from "../docker/statefulset";
import type { LocalAssistant } from "../../lockfile-contract";
import { localSourceCommandEntry, resolveBunExecutable } from "./common";
import { getLocalInstanceDir } from "./instance";

export function localExecDirForService(
  instanceDir: string,
  service: ServiceName,
): string {
  if (service === "gateway") {
    return join(instanceDir, "gateway-security");
  }
  if (service === "credential-executor") {
    return join(instanceDir, "ces-data");
  }
  return join(instanceDir, "workspace");
}

/**
 * The cadet binaries a local assistant's exec surface resolves from source,
 * as shim executables in the instance's own `bin/` dir: `assistant`,
 * `gateway`, `ces`, plus `credential-executor` (the CES binary's spelled-out
 * name). Everything else keeps the host PATH.
 */
const SHIMMED_COMMANDS = [
  "assistant",
  "gateway",
  "ces",
  "credential-executor",
] as const;

/**
 * Materialize the instance's XDG `bin/` folder: one executable shim per
 * cadet binary, each running that binary's source entry through bun — the
 * same resolution the daemon stack uses (`localSourceCommandEntry`), baked
 * at write time and refreshed by every hatch/wake/exec so an upgrade's new
 * runtime install is picked up. Exec prepends the returned dir to the
 * child's PATH, which fixes compound commands, pipes, and shell scripts
 * that invoke the binaries — argv rewriting only ever reached command[0].
 * A shim whose source cannot be resolved is simply not written and reported
 * in `unresolved`; exec turns that into an error for the command the user
 * actually ran, while hatch/wake treat shims as best-effort.
 */
export function ensureLocalBinShims(entry: LocalAssistant): {
  dir: string;
  unresolved: string[];
} {
  const dir = join(getLocalInstanceDir(entry), "bin");
  mkdirSync(dir, { recursive: true });
  const bunPath = resolveBunExecutable();
  const unresolved: string[] = [];
  for (const name of SHIMMED_COMMANDS) {
    const entryPath = localSourceCommandEntry(name, entry);
    if (!entryPath) {
      unresolved.push(name);
      continue;
    }
    const shim = join(dir, name);
    writeFileSync(
      shim,
      `#!/bin/sh\n# Generated by cadet — runs this binary from the local assistant's source.\nexec "${bunPath}" run "${entryPath}" "$@"\n`,
    );
    chmodSync(shim, 0o755);
  }
  return { dir, unresolved };
}
